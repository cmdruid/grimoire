const INPUTS: [(&str, &str); 5] = [
    ("UnicodeData.txt", "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"),
    ("CompositionExclusions.txt", "2f239196ef3b5b61db5cc476e9bd80f534d15aa1b74e1be1dea5d042a344c85f"),
    ("DerivedNormalizationProps.txt", "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488"),
    ("NormalizationTest.txt", "5019ffd530751a741900c849c0e010332f142a3612234639bd200b82138a87db"),
    ("LICENSE.txt", "e7a93b009565cfce55919a381437ac4db883e9da2126fa28b91d12732bc53d96"),
];

fn main() {
    let mut args = env::args_os().skip(1);
    let input = PathBuf::from(args.next().expect("usage: generate_unicode17 <input-dir> <output>"));
    let output = PathBuf::from(args.next().expect("usage: generate_unicode17 <input-dir> <output>"));
    assert!(args.next().is_none(), "usage: generate_unicode17 <input-dir> <output>");
    for (name, expected) in INPUTS {
        let bytes = fs::read(input.join(name))
            .unwrap_or_else(|error| panic!("read {}: {}", name, error));
        let actual = hex(&sha256(&bytes));
        assert_eq!(actual, expected, "refusing unpinned Unicode input {}", name);
    }
    let unicode_data = fs::read_to_string(input.join("UnicodeData.txt")).unwrap();
    let derived = fs::read_to_string(input.join("DerivedNormalizationProps.txt")).unwrap();
    let exclusions = fs::read_to_string(input.join("CompositionExclusions.txt")).unwrap();

    let mut ccc = BTreeMap::new();
    let mut decomposition = BTreeMap::new();
    for line in unicode_data.lines().filter(|line| !line.is_empty()) {
        let fields: Vec<_> = line.split(';').collect();
        let cp = u32::from_str_radix(fields[0], 16).unwrap();
        let class: u8 = fields[3].parse().unwrap();
        if class != 0 {
            ccc.insert(cp, class);
        }
        let mapping = fields[5];
        if !mapping.is_empty() && !mapping.starts_with('<') {
            decomposition.insert(cp, codepoints(mapping));
        }
    }

    let mut excluded = BTreeSet::new();
    for line in exclusions.lines() {
        let value = line.split('#').next().unwrap().trim();
        if !value.is_empty() {
            insert_range(&mut excluded, value);
        }
    }
    for line in derived.lines() {
        let value = line.split('#').next().unwrap().trim();
        if value.is_empty() {
            continue;
        }
        let fields: Vec<_> = value.split(';').map(str::trim).collect();
        if fields.get(1) == Some(&"Full_Composition_Exclusion") {
            insert_range(&mut excluded, fields[0]);
        }
    }

    let mut mappings = Vec::new();
    for line in derived.lines() {
        let value = line.split('#').next().unwrap().trim();
        if value.is_empty() {
            continue;
        }
        let fields: Vec<_> = value.split(';').map(str::trim).collect();
        if fields.get(1) != Some(&"NFKC_CF") {
            continue;
        }
        let (start, end) = parse_range(fields[0]);
        mappings.push((start, end, codepoints(fields.get(2).copied().unwrap_or_default())));
    }

    let mut composition = BTreeMap::new();
    for (&composed, parts) in &decomposition {
        if parts.len() == 2 && !excluded.contains(&composed) && ccc.get(&parts[0]).copied().unwrap_or(0) == 0 {
            composition.insert((parts[0], parts[1]), composed);
        }
    }

    let generated = render(&mappings, &decomposition, &ccc, &composition);
    fs::write(&output, generated).unwrap_or_else(|error| panic!("write {}: {error}", output.display()));
    let status = Command::new("rustfmt")
        .arg("--edition")
        .arg("2021")
        .arg(&output)
        .status()
        .unwrap_or_else(|error| panic!("run rustfmt: {}", error));
    assert!(status.success(), "rustfmt failed for {}", output.display());
}

fn render(
    mappings: &[(u32, u32, Vec<u32>)],
    decomposition: &BTreeMap<u32, Vec<u32>>,
    ccc: &BTreeMap<u32, u8>,
    composition: &BTreeMap<(u32, u32), u32>,
) -> String {
    let mut out = String::new();
    writeln!(out, "// @generated by tools/generate_unicode17.rs; Unicode 17.0.0.").unwrap();
    writeln!(out, "// Do not hand-edit. Regenerate only from the pinned tests/data/unicode-17 inputs.\n").unwrap();
    writeln!(out, "#[cfg(test)]\npub(crate) const UNICODE_VERSION: &str = \"17.0.0\";").unwrap();
    writeln!(out, "#[cfg(test)]\npub(crate) const NFKC_CF_RANGE_COUNT: usize = {};\n", mappings.len()).unwrap();
    writeln!(out, "const NFKC_CF: &[(u32, u32, &[u32])] = &[").unwrap();
    for (start, end, values) in mappings {
        writeln!(out, "    (0x{start:X}, 0x{end:X}, &{}),", slice(values)).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "const DECOMPOSITION: &[(u32, &[u32])] = &[").unwrap();
    for (cp, values) in decomposition {
        writeln!(out, "    (0x{cp:X}, &{}),", slice(values)).unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "const COMBINING_CLASS: &[(u32, u8)] = &[").unwrap();
    for (cp, class) in ccc {
        writeln!(out, "    (0x{cp:X}, {class}),").unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "const COMPOSITION: &[((u32, u32), u32)] = &[").unwrap();
    for ((first, second), composed) in composition {
        writeln!(out, "    ((0x{first:X}, 0x{second:X}), 0x{composed:X}),").unwrap();
    }
    writeln!(out, "];\n").unwrap();
    out.push_str(RUNTIME);
    out
}

