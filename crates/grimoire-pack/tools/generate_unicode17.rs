fn normalize_codepoints(mapped: Vec<u32>) -> String {
    let mut decomposed = Vec::new();
    for cp in mapped { decompose(cp, &mut decomposed); }
    reorder(&mut decomposed);
    compose(&decomposed).into_iter().filter_map(char::from_u32).collect()
}

fn decompose(cp: u32, out: &mut Vec<u32>) {
    const S_BASE: u32 = 0xAC00;
    const L_BASE: u32 = 0x1100;
    const V_BASE: u32 = 0x1161;
    const T_BASE: u32 = 0x11A7;
    const L_COUNT: u32 = 19;
    const V_COUNT: u32 = 21;
    const T_COUNT: u32 = 28;
    const N_COUNT: u32 = V_COUNT * T_COUNT;
    const S_COUNT: u32 = L_COUNT * N_COUNT;
    let index = cp.wrapping_sub(S_BASE);
    if index < S_COUNT {
        out.push(L_BASE + index / N_COUNT);
        out.push(V_BASE + (index % N_COUNT) / T_COUNT);
        let trail = index % T_COUNT;
        if trail != 0 { out.push(T_BASE + trail); }
    } else if let Ok(index) = DECOMPOSITION.binary_search_by_key(&cp, |(value, _)| *value) {
        for part in DECOMPOSITION[index].1 { decompose(*part, out); }
    } else {
        out.push(cp);
    }
}

fn combining_class(cp: u32) -> u8 {
    COMBINING_CLASS.binary_search_by_key(&cp, |(value, _)| *value).map_or(0, |index| COMBINING_CLASS[index].1)
}

fn reorder(values: &mut [u32]) {
    for index in 1..values.len() {
        let class = combining_class(values[index]);
        if class == 0 { continue; }
        let mut cursor = index;
        while cursor > 0 {
            let previous = combining_class(values[cursor - 1]);
            if previous == 0 || previous <= class { break; }
            values.swap(cursor - 1, cursor);
            cursor -= 1;
        }
    }
}

#[allow(clippy::manual_is_multiple_of)]
fn compose_pair(first: u32, second: u32) -> Option<u32> {
    const S_BASE: u32 = 0xAC00;
    const L_BASE: u32 = 0x1100;
    const V_BASE: u32 = 0x1161;
    const T_BASE: u32 = 0x11A7;
    const L_COUNT: u32 = 19;
    const V_COUNT: u32 = 21;
    const T_COUNT: u32 = 28;
    const N_COUNT: u32 = V_COUNT * T_COUNT;
    const S_COUNT: u32 = L_COUNT * N_COUNT;
    let l = first.wrapping_sub(L_BASE);
    let v = second.wrapping_sub(V_BASE);
    if l < L_COUNT && v < V_COUNT { return Some(S_BASE + (l * V_COUNT + v) * T_COUNT); }
    let s = first.wrapping_sub(S_BASE);
    let t = second.wrapping_sub(T_BASE);
    if s < S_COUNT && s % T_COUNT == 0 && t > 0 && t < T_COUNT { return Some(first + t); }
    COMPOSITION.binary_search_by_key(&(first, second), |(pair, _)| *pair).ok().map(|index| COMPOSITION[index].1)
}

fn compose(values: &[u32]) -> Vec<u32> {
    let Some(&first) = values.first() else { return Vec::new(); };
    let mut out = vec![first];
    let mut starter = 0usize;
    let mut last_class = combining_class(first);
    for &cp in &values[1..] {
        let class = combining_class(cp);
        if let Some(composed) = compose_pair(out[starter], cp).filter(|_| last_class == 0 || last_class < class) {
            out[starter] = composed;
        } else {
            if class == 0 { starter = out.len(); }
            out.push(cp);
            last_class = class;
        }
    }
    out
}
