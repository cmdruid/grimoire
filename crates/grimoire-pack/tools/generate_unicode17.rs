fn slice(values: &[u32]) -> String {
    let mut out = String::from("[");
    for (index, value) in values.iter().enumerate() {
        if index != 0 { out.push_str(", "); }
        write!(out, "0x{value:X}").unwrap();
    }
    out.push(']');
    out
}

fn codepoints(value: &str) -> Vec<u32> {
    value
        .split_whitespace()
        .map(|part| u32::from_str_radix(part, 16).unwrap())
        .collect()
}

fn parse_range(value: &str) -> (u32, u32) {
    if let Some((start, end)) = value.split_once("..") {
        (u32::from_str_radix(start, 16).unwrap(), u32::from_str_radix(end, 16).unwrap())
    } else {
        let value = u32::from_str_radix(value, 16).unwrap();
        (value, value)
    }
}

fn insert_range(set: &mut BTreeSet<u32>, value: &str) {
    let (start, end) = parse_range(value);
    set.extend(start..=end);
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

